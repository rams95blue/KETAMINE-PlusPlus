#!/usr/bin/env python3
"""Generates the MinGW equivalents of src/winmm_stubs.asm and the #pragma exports in src/winmm_exports.h:
build-mingw/winmm_stubs.S (GNU assembler) and build-mingw/winmm.def (exports with the same names and ordinals)."""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)
text = (src / "winmm_exports.h").read_text()
exports = re.findall(r'#pragma comment\(linker, "/EXPORT:([^=]+)=KmStub(\d+),@(\d+)(,NONAME)?"\)', text)
count = int(re.search(r"kWinmmCount = (\d+)", text).group(1))
assert len(exports) == count, (len(exports), count)

with open(out / "winmm_stubs.S", "w") as f:
    f.write("# Generated by tools/gen_mingw_proxy.py: one stub per winmm export, jumping to the real function.\n")
    f.write("    .text\n")
    for i in range(count):
        f.write(f"    .globl KmStub{i}\n    .p2align 4\nKmStub{i}:\n    jmp *g_kmWinmm+{i * 8}(%rip)\n")

with open(out / "winmm.def", "w") as f:
    f.write("LIBRARY winmm.dll\nEXPORTS\n")
    for name, stub, ordinal, noname in exports:
        f.write(f"    {name}=KmStub{stub} @{ordinal}{' NONAME' if noname else ''}\n")
print(f"{count} stubs and exports written to {out}")
